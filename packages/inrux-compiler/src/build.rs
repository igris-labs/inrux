//! Deterministic Cargo integration rooted at one explicitly imported component graph.
use crate::{SourceFile, compile_source, imports, sfc};
use std::{
    collections::{BTreeMap, BTreeSet, VecDeque},
    fs,
    path::{Path, PathBuf},
    sync::Arc,
};

type Error = Box<dyn std::error::Error>;
/// Files generated for the reachable component graph.
#[derive(Debug)]
pub struct BuildOutput {
    /// Include this file once at the application crate root.
    pub bootstrap: PathBuf,
    /// Original sources, in deterministic module order.
    pub sources: Vec<PathBuf>,
}

/// Compile `App.iru` and explicitly imported `.iru` modules into Rust module files and one bootstrap.
///
/// Module imports use `crate::components::counter as Counter` for `components/Counter.iru`.
/// Ordinary Rust modules remain declared in main.rs. Imported candidates are included even
/// when selected only in a runtime conditional; unimported source files are never compiled.
/// Cargo watches source directories too, so additions, removals, and renames rebuild the graph.
///
/// # Errors
/// Reports filesystem errors, module-name collisions, and original-source syntax failures.
pub fn build_app(entry: impl AsRef<Path>, output: impl AsRef<Path>) -> Result<BuildOutput, Error> {
    let entry = entry.as_ref().canonicalize()?;
    let root = entry.parent().ok_or("App.iru needs a source directory")?;
    let mut available = BTreeMap::new();
    discover(root, root, &mut available)?;
    let entry_name = module_path(root, &entry)?;
    let mut pending = VecDeque::from([entry_name]);
    let mut generated = BTreeMap::new();
    let mut sources = Vec::new();
    let mut metadata = BTreeMap::new();
    while let Some(module) = pending.pop_front() {
        if generated.contains_key(&module) {
            continue;
        }
        let path = available
            .get(&module)
            .ok_or("Cannot resolve root component")?;
        println!("cargo::rerun-if-changed={}", path.display());
        let source = Arc::new(SourceFile::new(path, fs::read_to_string(path)?));
        let compiled = compile_source((*source).clone())?;
        let blocks = sfc::parse(&source)?;
        let original = &source.text()[blocks.rust.body.clone()];
        let rust = syn::parse_file(original)?;
        // Preserve authored bytes for IDE mappings instead of guessing through pretty-print changes.
        let prefix = prettyplease::unparse(&rust);
        let suffix = compiled
            .strip_prefix(&prefix)
            .ok_or("Cannot map generated Rust prefix")?;
        let compiled = format!("{original}\n{suffix}");
        metadata.insert(
            module.clone(),
            (path.clone(), source.text().to_owned(), blocks.rust.body),
        );
        for import in imports::imports(&rust).into_values() {
            let resolved = resolve(&module, &import);
            if available.contains_key(&resolved) {
                pending.push_back(resolved);
            }
        }
        generated.insert(module, compiled);
        sources.push(path.clone());
    }
    let mut body = String::from("// Generated by Inrux. Edit the original .iru files.\n");
    fs::create_dir_all(output.as_ref())?;
    let output = output.as_ref().canonicalize()?;
    let mut module_files = BTreeMap::new();
    emit_modules(&generated, &[], &mut body, &output, &mut module_files)?;
    body.push_str("/// Global styles from reachable components in deterministic module order.\npub fn inrux_global_styles() -> Vec<::inrux::Rule> { let mut rules = Vec::new();\n");
    for module in generated.keys() {
        body.push_str(&format!(
            "rules.extend({}::global_styles());\n",
            module.join("::")
        ));
    }
    body.push_str("rules }\n");
    let bootstrap = output.join("inrux_app.rs");
    fs::write(&bootstrap, body)?;
    let mappings: Vec<_> = metadata
        .into_iter()
        .map(|(module, (source, text, range))| {
            serde_json::json!({"source":source,"sourceText":text,"originalStart":range.start,
            "originalEnd":range.end,"generated":module_files[&module],"generatedStart":0,
            "generatedEnd":range.len()})
        })
        .collect();
    fs::write(
        output.join("inrux_app.map.json"),
        serde_json::to_vec(&serde_json::json!({
            "version":1,"entry":entry,"generated":bootstrap,"mappings":mappings
        }))?,
    )?;
    sources.sort();
    Ok(BuildOutput { bootstrap, sources })
}

/// Resolve crate/self/super paths without imposing special syntax on ordinary Rust imports.
fn resolve(current: &[String], import: &[String]) -> Vec<String> {
    let mut base = current[..current.len().saturating_sub(1)].to_vec();
    let mut rest = import;
    match import.first().map(String::as_str) {
        Some("crate") => {
            base.clear();
            rest = &import[1..];
        }
        Some("self") => {
            base = current.to_vec();
            rest = &import[1..];
        }
        Some("super") => {
            base = current.to_vec();
            while rest.first().is_some_and(|part| part == "super") {
                base.pop();
                rest = &rest[1..];
            }
        }
        _ => return import.to_vec(),
    }
    base.extend_from_slice(rest);
    base
}

/// Discover names without reading or validating unreachable component bodies.
fn discover(
    root: &Path,
    directory: &Path,
    files: &mut BTreeMap<Vec<String>, PathBuf>,
) -> Result<(), Error> {
    println!("cargo::rerun-if-changed={}", directory.display());
    let mut entries = fs::read_dir(directory)?.collect::<Result<Vec<_>, _>>()?;
    entries.sort_by_key(|entry| entry.file_name());
    for entry in entries {
        let path = entry.path();
        if entry.file_type()?.is_symlink() {
            continue;
        }
        if path.is_dir() {
            discover(root, &path, files)?;
        } else if path.extension().is_some_and(|extension| extension == "iru") {
            let module = module_path(root, &path)?;
            if let Some(previous) = files.insert(module, path.clone()) {
                return Err(format!(
                    "Component module collision: {} and {}",
                    previous.display(),
                    path.display()
                )
                .into());
            }
        }
    }
    Ok(())
}

/// Derive validated Rust module paths from a component's relative path.
fn module_path(root: &Path, path: &Path) -> Result<Vec<String>, Error> {
    path.strip_prefix(root)?
        .with_extension("")
        .components()
        .map(|part| {
            let name = imports::module_name(&part.as_os_str().to_string_lossy());
            syn::parse_str::<syn::Ident>(&name)
                .map_err(|_| format!("Invalid component module name `{name}`"))?;
            Ok(name)
        })
        .collect()
}

/// Emit each folder once, rejecting file/folder module collisions before writing output.
fn emit_modules(
    files: &BTreeMap<Vec<String>, String>,
    parent: &[String],
    output: &mut String,
    directory: &Path,
    module_files: &mut BTreeMap<Vec<String>, PathBuf>,
) -> Result<(), Error> {
    let names: BTreeSet<_> = files
        .keys()
        .filter(|&path| path.starts_with(parent) && path.len() > parent.len())
        .map(|path| path[parent.len()].clone())
        .collect();
    for name in names {
        let mut path = parent.to_vec();
        path.push(name.clone());
        if let Some(body) = files.get(&path) {
            if files
                .keys()
                .any(|other| other.starts_with(&path) && other.len() > path.len())
            {
                return Err(format!(
                    "Component and folder both generate module {}",
                    path.join("::")
                )
                .into());
            }
            // Ordinary module files give rust-analyzer a native file context for body inference.
            let generated = directory
                .join("inrux_modules")
                .join(path.join("/"))
                .with_extension("rs");
            fs::create_dir_all(
                generated
                    .parent()
                    .ok_or("Generated module needs a parent")?,
            )?;
            fs::write(&generated, body)?;
            output.push_str(&format!(
                "#[path = {:?}] pub mod {name};\n",
                generated.to_string_lossy()
            ));
            module_files.insert(path, generated);
        } else {
            output.push_str(&format!("pub mod {name} {{\n"));
            emit_modules(files, &path, output, directory, module_files)?;
            output.push_str("}\n");
        }
    }
    Ok(())
}
